
import os
import sys
import pandas as pd
import matplotlib.pyplot as plt

# --------------------------------------------------
# CONFIGURATION
# --------------------------------------------------

CSV_FILE = "results.csv"
OUTPUT_DIR = "graphs"

# --------------------------------------------------
# LOAD DATA
# --------------------------------------------------

if not os.path.exists(CSV_FILE):
    print("ERROR: results.csv not found.")
    print("Run your C++ allocator first.")
    sys.exit(1)

df = pd.read_csv(CSV_FILE)

required_columns = [
    "threads",
    "mutex_ops_sec",
    "cas_ops_sec",
    "mutex_avg_latency_ns",
    "cas_avg_latency_ns",
    "cas_retries",
    "peak_internal_waste_bytes",
]

missing = [
    column for column in required_columns
    if column not in df.columns
]

if missing:
    print("Missing CSV columns:", missing)
    print("Check that results.csv was generated by Phase 2.")
    sys.exit(1)

os.makedirs(OUTPUT_DIR, exist_ok=True)

# Professional-looking chart defaults
plt.rcParams["figure.figsize"] = (9, 5.5)
plt.rcParams["font.size"] = 10
plt.rcParams["axes.grid"] = True
plt.rcParams["grid.alpha"] = 0.25

MUTEX_COLOR = "#2563EB"
CAS_COLOR = "#0D9488"


def save_chart(filename):
    """Save the current chart as a high-resolution PNG."""
    plt.tight_layout()
    path = os.path.join(OUTPUT_DIR, filename)
    plt.savefig(path, dpi=180, bbox_inches="tight")
    print("Saved:", path)
    plt.close()


# --------------------------------------------------
# GRAPH 1: THROUGHPUT VS THREAD COUNT
# --------------------------------------------------

plt.plot(
    df["threads"],
    df["mutex_ops_sec"],
    marker="o",
    linewidth=2.5,
    color=MUTEX_COLOR,
    label="Mutex allocator",
)

plt.plot(
    df["threads"],
    df["cas_ops_sec"],
    marker="s",
    linewidth=2.5,
    color=CAS_COLOR,
    label="CAS allocator",
)

plt.title("Allocator Throughput vs Thread Count")
plt.xlabel("Number of threads")
plt.ylabel("Operations per second")
plt.xticks(df["threads"])
plt.legend()

save_chart("01_throughput.png")


# --------------------------------------------------
# GRAPH 2: AVERAGE LATENCY VS THREAD COUNT
# --------------------------------------------------

plt.plot(
    df["threads"],
    df["mutex_avg_latency_ns"],
    marker="o",
    linewidth=2.5,
    color=MUTEX_COLOR,
    label="Mutex allocator",
)

plt.plot(
    df["threads"],
    df["cas_avg_latency_ns"],
    marker="s",
    linewidth=2.5,
    color=CAS_COLOR,
    label="CAS allocator",
)

plt.title("Average Operation Latency vs Thread Count")
plt.xlabel("Number of threads")
plt.ylabel("Nanoseconds per operation")
plt.xticks(df["threads"])
plt.legend()

save_chart("02_latency.png")


# --------------------------------------------------
# GRAPH 3: CAS RETRIES VS THREAD COUNT
# --------------------------------------------------

plt.bar(
    df["threads"].astype(str),
    df["cas_retries"],
    color="#D97706",
    width=0.6,
)

plt.title("CAS Retry Count vs Thread Count")
plt.xlabel("Number of threads")
plt.ylabel("Failed CAS attempts")
save_chart("03_cas_retries.png")


# --------------------------------------------------
# GRAPH 4: ESTIMATED INTERNAL FRAGMENTATION
# --------------------------------------------------

plt.plot(
    df["threads"],
    df["peak_internal_waste_bytes"] / 1024,
    marker="D",
    linewidth=2.5,
    color="#8B5CF6",
)

plt.title("Estimated Peak Internal Memory Waste")
plt.xlabel("Number of threads")
plt.ylabel("Estimated unused bytes (KiB)")
plt.xticks(df["threads"])

save_chart("04_memory_waste.png")


# --------------------------------------------------
# GRAPH 5: THROUGHPUT SPEEDUP
# --------------------------------------------------

# Speedup is measured against the mutex result
# at the same thread count.

safe_mutex = df["mutex_ops_sec"].replace(0, float("nan"))

df["throughput_ratio"] = (
    df["cas_ops_sec"] / safe_mutex
)

plt.bar(
    df["threads"].astype(str),
    df["throughput_ratio"],
    color=[
        CAS_COLOR if value >= 1 else MUTEX_COLOR
        for value in df["throughput_ratio"].fillna(0)
    ],
)

plt.axhline(
    y=1,
    color="black",
    linestyle="--",
    linewidth=1,
    label="Equal throughput",
)

plt.title("CAS-to-Mutex Throughput Ratio")
plt.xlabel("Number of threads")
plt.ylabel("CAS throughput / Mutex throughput")
plt.legend()

save_chart("05_throughput_ratio.png")


# --------------------------------------------------
# SUMMARY
# --------------------------------------------------

print("\n========================================")
print(" ALLOCATOR VISUALIZATION COMPLETE")
print("========================================")

print("\nBenchmark summary:")
print(
    df[
        [
            "threads",
            "mutex_ops_sec",
            "cas_ops_sec",
            "mutex_avg_latency_ns",
            "cas_avg_latency_ns",
        ]
    ].to_string(index=False)
)

print("\nAll graphs are saved in:", OUTPUT_DIR)
print("Use these PNG files in your project PPT.")